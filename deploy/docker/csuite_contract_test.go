func TestMikePromptAllowsStandingTestReviewAuthority(t *testing.T) {
	root := repoRoot(t)
	paths := []string{filepath.Join(root, "docs", "csuite-agents", "prompts", "mike.md")}
	stagedPrompt := filepath.Join(root, "deploy", "docker", "context", "csuite-prompts", "mike.md")
	if _, err := os.Stat(stagedPrompt); err == nil {
		paths = append(paths, stagedPrompt)
	} else if !os.IsNotExist(err) {
		t.Fatalf("stat staged Mike prompt %s: %v", stagedPrompt, err)
	}

	for _, path := range paths {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read Mike prompt %s: %v", path, err)
		}
		content := string(data)
		for _, required := range []string{
			"Gate Authorization Protocol",
			"standing autonomous `test_review` authority",
			"plans/mike-standing-test-review-authority.md",
			"Bare `ops-relay` `status_change` notifications for `plan_review` are visibility",
			"dremctl approve <task-id-prefix>",
			"dremctl reject <task-id-prefix> --reason",
		} {
			if !strings.Contains(content, required) {
				t.Fatalf("Mike prompt %s must contain %q", path, required)
			}
		}
		if strings.Contains(content, "Approve or reject tasks at human gates (other than") {
			t.Fatalf("Mike prompt %s still contains the old absolute gate-action prohibition", path)
		}
	}

	// The Docker context is intentionally generated by build-csuite.sh and is
	// absent in a clean checkout. Prove the canonical prompt is staged by the
	// supported build entry point instead of requiring generated files to be
	// committed before `go test ./...` can pass.
	buildScriptPath := filepath.Join(root, "deploy", "docker", "build-csuite.sh")
	buildScript, err := os.ReadFile(buildScriptPath)
	if err != nil {
		t.Fatalf("read C-Suite build script: %v", err)
	}
	for _, required := range []string{
		`PROMPT_SRC="docs/csuite-agents/prompts"`,
		`PROMPT_DST="deploy/docker/context/csuite-prompts"`,
		`cp "${PROMPT_SRC}/${persona}.md" "${PROMPT_DST}/${persona}.md"`,
	} {
		if !strings.Contains(string(buildScript), required) {
			t.Fatalf("C-Suite build script must stage Mike's canonical prompt via %q", required)
		}
	}
}

