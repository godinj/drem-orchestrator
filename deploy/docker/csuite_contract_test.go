func TestWorkerBaseTrustsOnlyTheMountedBareRepository(t *testing.T) {
	root := repoRoot(t)
	path := filepath.Join(root, "deploy", "docker", "worker-base.Dockerfile")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read worker-base Dockerfile: %v", err)
	}
	contents := string(data)
	if !strings.Contains(contents, "git config --system --add safe.directory /bare") {
		t.Fatal("worker-base must trust the fixed /bare mount for cross-UID macOS hosts")
	}
	if strings.Contains(contents, "safe.directory '*'") || strings.Contains(contents, "safe.directory \"*\"") {
		t.Fatal("worker-base must not disable Git ownership checks globally")
	}
}

