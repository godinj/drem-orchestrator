func TestStaticServiceDockerfilesHonorBuildTargetArchitecture(t *testing.T) {
	root := repoRoot(t)
	files := []string{
		"spawner.Dockerfile",
		"agentmon.Dockerfile",
		"kyle.Dockerfile",
		"docker-query-proxy.Dockerfile",
		"gq.Dockerfile",
	}

	for _, name := range files {
		t.Run(name, func(t *testing.T) {
			path := filepath.Join(root, "deploy", "docker", name)
			data, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("read %s: %v", name, err)
			}
			contents := string(data)
			for _, required := range []string{"ARG TARGETOS", "ARG TARGETARCH", "GOOS=${TARGETOS}", "GOARCH=${TARGETARCH}"} {
				if !strings.Contains(contents, required) {
					t.Fatalf("%s must contain %q", name, required)
				}
			}
			if strings.Contains(contents, "GOARCH=amd64") {
				t.Fatalf("%s must not hard-code amd64", name)
			}
		})
	}
}
